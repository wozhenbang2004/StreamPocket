"""Convert retained Lucide 0.468.0 nodes to Android paths. Requires fonttools 4.61.1."""
import json
from pathlib import Path
from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[1]


def path_data(kind, node):
    if kind == "path":
        return node["d"]
    if kind in ("polyline", "polygon"):
        return "M" + node["points"] + ("Z" if kind == "polygon" else "")
    if kind == "line":
        return f'M{node["x1"]},{node["y1"]}L{node["x2"]},{node["y2"]}'
    if kind == "circle":
        x, y, r = (float(node[k]) for k in ("cx", "cy", "r"))
        return f"M{x-r},{y}a{r},{r} 0 1 0 {2*r},0a{r},{r} 0 1 0 {-2*r},0Z"
    if kind == "rect":
        x, y, w, h = (float(node.get(k, 0)) for k in ("x", "y", "width", "height"))
        r = min(float(node.get("rx", 0)), w / 2, h / 2)
        if not r:
            return f"M{x},{y}h{w}v{h}h{-w}Z"
        return (f"M{x+r},{y}h{w-2*r}a{r},{r} 0 0 1 {r},{r}v{h-2*r}"
                f"a{r},{r} 0 0 1 {-r},{r}h{-w+2*r}a{r},{r} 0 0 1 {-r},{-r}"
                f"v{-h+2*r}a{r},{r} 0 0 1 {r},{-r}Z")
    raise ValueError(f"Unsupported Lucide node: {kind}")


data = json.loads((ROOT / "docs/design/upstream/lucide/icon-nodes.json").read_text())
cases = []
for name, icon in data["icons"].items():
    pen = RecordingPen()
    for kind, node in icon["nodes"]:
        parse_path(path_data(kind, node), pen)
    operations = []
    for op, points in pen.value:
        if op == "endPath":
            continue
        method = {"moveTo": "moveTo", "lineTo": "lineTo", "curveTo": "cubicTo", "qCurveTo": "quadTo", "closePath": "close"}[op]
        args = ",".join(f"{value:.6f}f" for point in points for value in point)
        operations.append(f"                path.{method}({args});")
    cases.append(f'            case "{name}":\n' + "\n".join(operations) + "\n                break;")

